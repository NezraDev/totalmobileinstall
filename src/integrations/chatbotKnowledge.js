const serviceById = Object.fromEntries(
  services.map((service) => [service.id, service]),
);

function serviceAction(id) {
  const service = serviceById[id];
  return {
    label: `About ${service.name.toLowerCase()}`,
    href: `/services/${service.id}`,
    icon: 'arrow',
  };
}

function serviceFacts(id) {
  const service = serviceById[id];
  const points = service.points?.length
    ? ` Highlights: ${service.points.join('; ')}.`
    : '';
  return `${service.description} ${service.detail}${points}`;
}

