function normalize(value) {
  return String(value ?? '')
    .replace(/\bcan['’]t\b/gi, 'cannot')
    .replace(/\bdon['’]t\b/gi, 'do not')
    .replace(/\bdoesn['’]t\b/gi, 'does not')
    .replace(/\bdidn['’]t\b/gi, 'did not')
    .replace(/\bwon['’]t\b/gi, 'will not')
    .replace(/\bisn['’]t\b/gi, 'is not')
    .replace(/\baren['’]t\b/gi, 'are not')
    .replace(/\bwouldn['’]t\b/gi, 'would not')
    .replace(/\bshouldn['’]t\b/gi, 'should not')
    .replace(/\bcouldn['’]t\b/gi, 'could not')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

function matchScore(query, triggers, ruleId) {
  const paddedQuery = ` ${query} `;
  let best = 0;
  for (const trigger of triggers) {
    const phrase = normalize(trigger);
    if (
      ruleId === 'services-list' &&
      ['service', 'services'].includes(phrase) &&
      query !== phrase
    )
      continue;
    if (phrase && paddedQuery.includes(` ${phrase} `))
      best = Math.max(best, phrase.length);
  }
  return best;
}

export function getChatbotReply(question) {
  const query = normalize(question);
  if (!query) {
    return {
      text: 'Type a question about our services, service area, shop, hours, or booking.',
      actions: [],
    };
  }

  let match = rules
    .map((rule) => ({
      rule,
      phraseScore: matchScore(query, rule.triggers, rule.id),
    }))
    .filter(({ phraseScore }) => phraseScore > 0)
    .sort(
      (a, b) =>
        b.rule.priority - a.rule.priority || b.phraseScore - a.phraseScore,
    )[0];

  const mentionsTint = /\btint(?:ed|ing)?\b|\bwindow film\b/.test(query);
  const asksTintLegality =
    mentionsTint &&
    /\b(?:legal|law|allowed|percentage|percent|darkest|dark)\b/.test(query);
  if (asksTintLegality) {
    const legalRuleId = /\b(?:windshield|windscreen)\b/.test(query)
      ? 'windshield-tint-guidance'
      : 'tint-law';
    const legalRule = rules.find((rule) => rule.id === legalRuleId);
    if (!match || match.rule.priority < legalRule.priority)
      match = { rule: legalRule, phraseScore: 1 };
  }

  const asksLocation =
    /\b(?:service|mobile|cover|serve|visit|come|travel|availability|area|zip|postal|shop|address|location|directions)\b/.test(
      query,
    );
  const includesZipCode = /\b\d{5}\b/.test(query) && asksLocation;
  const zipAreaRule = rules.find((rule) => rule.id === 'service-area');

  if (
    includesZipCode &&
    (!match ||
      [
        'services-list',
        'mobile-service',
        'mobile-vs-shop',
        'vehicle-types',
      ].includes(match.rule.id))
  )
    return zipAreaRule.reply();

  if (match) {
    const response = match.rule.reply();
    if (includesZipCode && match.rule.id !== 'service-area') {
      return {
        ...response,
        text: `${response.text} The team can confirm service availability for your ZIP code.`,
        actions: [
          ...response.actions,
          serviceAreaAction,
          ...contactActions,
        ].filter(
          (action, index, all) =>
            all.findIndex((item) => item.href === action.href) === index,
        ),
      };
    }
    return response;
  }

  if (includesZipCode) return zipAreaRule.reply();

  return {
    text: `I don’t have a confirmed answer for that yet. Call ${business.phone} or email ${business.email}, and the team can help with your concern.`,
    actions: contactActions,
  };
}

